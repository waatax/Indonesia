// Step B: Extract structured vocab & phrase pairs from data.json & quest/course/*.json
function registerExtracted(idRaw, zhRaw, pos = '') {
  if (!idRaw || !zhRaw || typeof idRaw !== 'string' || typeof zhRaw !== 'string') return;
  // Handle slash-separated variants like "Tidak / Gak"
  const variants = idRaw.split('/').map(v => normKey(v)).filter(Boolean);
  const zh = cleanZh(zhRaw);
  if (!zh || !/[\u4e00-\u9fa5]/.test(zh)) return;

  for (const k of variants) {
    if (k.length < 2 || k.length > 36) continue;
    if (/[^a-z\u00e0-\u00ff\s-]/.test(k)) continue;
    const wc = k.split(' ').length;
    if (wc === 1) {
      if (!words.has(k)) words.set(k, pos ? `${zh}|${pos}` : zh);
    } else if (wc <= 3) {
      if (!phrases.has(k)) phrases.set(k, zh);
    }
  }
}

const dataJson = JSON.parse(fs.readFileSync('data.json', 'utf8'));
const walkExtract = (obj) => {
  if (!obj || typeof obj !== 'object') return;
  if (Array.isArray(obj)) { obj.forEach(walkExtract); return; }
  if (obj.id && obj.zh) registerExtracted(obj.id, obj.zh);
  if (obj.indo && obj.zh) registerExtracted(obj.indo, obj.zh);
  if (obj.w && obj.zh) registerExtracted(obj.w, obj.zh);
  if (obj.id_word && obj.zh_word) registerExtracted(obj.id_word, obj.zh_word, POS_SHORT[obj.pos] || '');
  if (obj.gaul && obj.zh) registerExtracted(obj.gaul, obj.zh, '俚');
  if (obj.baku && obj.zh) registerExtracted(obj.baku, obj.zh);
  if (obj.abbr && obj.zh) registerExtracted(obj.abbr, obj.zh, '縮');
  if (obj.particle && obj.zh) registerExtracted(obj.particle, obj.zh, '助');
  if (obj.word && obj.meaning) registerExtracted(obj.word, obj.meaning);
  Object.values(obj).forEach(walkExtract);
};
walkExtract(dataJson);

for (const f of fs.readdirSync('quest/course')) {
  if (f.endsWith('.json')) {
    walkExtract(JSON.parse(fs.readFileSync(path.join('quest/course', f), 'utf8')));
  }
}

// Step C: Apply curated core words & phrases (highest priority)
for (const [k, v] of Object.entries(CORE_WORDS)) {
  words.set(normKey(k), v);
}
for (const [k, v] of Object.entries(CORE_PHRASES)) {
  phrases.set(normKey(k), v);
}

