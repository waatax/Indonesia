// Helper to normalize key
function normKey(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[?.!,"'()（）\[\]{}「」『』]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

// Helper to clean zh translation (keep concise for instant tooltip!)
function cleanZh(s) {
  let t = String(s || '').trim();
  // Remove overly long parenthetical notes if > 24 chars
  if (t.length > 26) {
    t = t.replace(/（[^）]{10,}）/g, '').replace(/\([^)]{10,}\)/g, '').trim();
  }
  if (t.length > 30) {
    // Take first 2 meanings split by / or ； or ，
    const parts = t.split(/[／/；;]/).map(x => x.trim()).filter(Boolean);
    if (parts.length > 1) t = parts.slice(0, 2).join(' / ');
  }
  return t.slice(0, 34).trim();
}

